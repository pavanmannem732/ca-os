import asyncio
import logging
from datetime import date, datetime, timezone
from sqlalchemy import select, func, update
from sqlalchemy.ext.asyncio import AsyncSession
from app.core.database import SessionLocal
from app.models.billing import BillingLog, Invoice, InvoiceStatus
from app.models.client import Client
from app.models.notification import NotificationChannel
from app.services.notification_service import notification_service

logger = logging.getLogger(__name__)

async def run_billing_agent():
    """
    Agent 3: Billing Agent (Section 9.4)
    Monitors unbilled logs and generates draft invoices.
    Typically runs every Friday at 6 PM.
    """
    logger.info("Starting Billing Agent run...")
    
    async with SessionLocal() as db:
        try:
            # 1. Find all unbilled billable logs
            stmt = select(BillingLog).where(
                BillingLog.is_billable == True,
                BillingLog.invoice_id.is_(None)
            )
            result = await db.execute(stmt)
            unbilled_logs = result.scalars().all()
            
            if not unbilled_logs:
                logger.info("No unbilled logs found.")
                return

            # 2. Group by (firm_id, client_id)
            client_logs = {}
            for log in unbilled_logs:
                key = (log.firm_id, log.client_id)
                if key not in client_logs:
                    client_logs[key] = []
                client_logs[key].append(log)
            
            logger.info(f"Generating draft invoices for {len(client_logs)} clients.")
            
            for (firm_id, client_id), logs in client_logs.items():
                total_amount = sum(log.billable_amount for log in logs)
                
                # Create draft invoice
                invoice_number = f"INV-{date.today().strftime('%Y%m')}-{str(client_id)[:4].upper()}"
                
                from datetime import timedelta
                new_invoice = Invoice(
                    firm_id=firm_id,
                    client_id=client_id,
                    invoice_number=invoice_number,
                    invoice_date=date.today(),
                    due_date=date.today() + timedelta(days=7),
                    subtotal=total_amount,
                    tax_amount=total_amount * 0.18, # 18% GST
                    total_amount=total_amount * 1.18,
                    status=InvoiceStatus.DRAFT,
                    notes=f"Draft generated by AI Billing Agent for {len(logs)} tasks."
                )
                db.add(new_invoice)
                await db.flush() # Get invoice ID
                
                # Link logs to this invoice
                for log in logs:
                    log.invoice_id = new_invoice.id
                
                logger.info(f"Generated draft invoice {invoice_number} for ₹{new_invoice.total_amount}")
                
                # Notify Firm Owner (Mocked)
                await notification_service.send_notification(
                    db, firm_id, 
                    message=f"Draft invoice {invoice_number} generated for client. Please review and send.",
                    notification_type="billing_alert",
                    recipient_user_id=None, # In production, target firm owner
                    preferred_channel=NotificationChannel.IN_APP
                )
            
            await db.commit()
            logger.info("Billing Agent run completed.")
            
        except Exception as e:
            logger.error(f"Error in Billing Agent: {e}")
            await db.rollback()

if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    asyncio.run(run_billing_agent())
